def 调用模型(prompt, key, model, img_b64=None, mime=None, temperature=TEMPERATURE, max_tokens=None,
            max_retries=3, 关思考=False):
    """统一调用模型接口，OpenAI 兼容格式。img_b64 传了就按多模态（图片+文本），否则纯文本。
    关思考=True 时显式关闭思考模式，少生成一大段推理文字，识别快很多。
    模型没开通（ModelNotOpen）不重试，直接把原因抛给上层，免得白等三分钟。"""
    url = "https://ark.cn-beijing.volces.com/api/v3/chat/completions"
    headers = {"Authorization": f"Bearer {key}", "Content-Type": "application/json"}
    if img_b64:
        content = [
            {"type": "image_url", "image_url": {"url": f"data:{mime};base64,{img_b64}"}},
            {"type": "text", "text": prompt},
        ]
    else:
        content = prompt  # 纯文本直接用字符串
    payload = {
        "model": model,
        "temperature": temperature,
        "messages": [{"role": "user", "content": content}],
    }
    if max_tokens:
        payload["max_tokens"] = max_tokens
    if 关思考:
        payload["thinking"] = {"type": "disabled"}

    最后的错误 = ""
    for attempt in range(max_retries):
        try:
            r = requests.post(url, headers=headers, json=payload, timeout=300)
            if r.status_code == 200:
                体 = r.json()
                raw = (体["choices"][0]["message"].get("content") or "").strip()
                if raw.startswith("```"):
                    raw = raw.split("\n", 1)[1] if "\n" in raw else raw
                    raw = raw.rsplit("```", 1)[0]
                if not raw.strip():
                    # 开了思考但 max_tokens 给得太小，思考过程把额度吃光、正文为空
                    最后的错误 = f"「{model}」返回正文为空（思考过程可能占满了 max_tokens={max_tokens}）"
                    break
                return raw.strip()
            # 接口的错误体是 {"error": {"code": "ModelNotOpen", "message": "..."}}
            try:
                体 = r.json()
            except Exception:
                体 = {}
            错误体 = 体.get("error") if isinstance(体.get("error"), dict) else 体
            code, msg = 错误体.get("code"), (错误体.get("message") or "")
            最后的错误 = f"HTTP {r.status_code} {code}：{str(msg)[:200]}"
            if code == "ModelNotOpen" or "has not activated" in str(msg):
                raise Exception(f"模型「{model}」没有开通：去控制台开通这个模型，再回来重试")
            if r.status_code == 429:
                time.sleep(10 + attempt * 10)     # 限流：退避后重试
                continue
            if r.status_code >= 500:
                time.sleep(3 + attempt * 3)       # 平台侧抖动：短退避重试
                continue
            break                                  # 参数/权限类 4xx，重试没意义
        except requests.exceptions.RequestException as e:
            最后的错误 = str(e)
            if attempt == max_retries - 1:
                break
            time.sleep(5)
    raise Exception(f"「{model}」多次调用仍失败：{最后的错误}")

def 调用模型带回退(prompt, key, 模型链, img_b64=None, mime=None, temperature=TEMPERATURE, max_tokens=None,
                  校验=None, 关思考=False):
    """依次尝试一组模型；调用异常、或返回内容通不过校验（如不是 JSON）时自动切换下一个模型。"""
    最后的错误 = ""
    最后的原始 = ""
    for model in 模型链:
        try:
            raw = 调用模型(prompt, key, model, img_b64=img_b64, mime=mime,
                            temperature=temperature, max_tokens=max_tokens, 关思考=关思考)
            if 校验 is not None:
                ok, reason = 校验(raw)
                if not ok:
                    最后的错误 = f"「{model}」返回内容未通过校验（{reason}）"
                    最后的原始 = raw
                    continue
            return raw
        except Exception as e:
            最后的错误 = str(e)
    if 最后的原始:
        raise Exception(f"返回内容不是有效 JSON（多个模型均失败）。最后返回内容开头：{最后的原始[:200]}")
    raise Exception(f"多个模型调用均失败（先检查：① 模型是否已在控制台开通 ② Key 是否有该模型权限 ③ 额度/余额是否用完）：{最后的错误}")

def 解析(raw):
    """尽量把模型输出解析为 Python 对象：直接解析 → 从文本中截取最外层 JSON 片段再解析。"""
    if not isinstance(raw, str):
        return None, raw
    raw = raw.strip()
    for fn in (json.loads, ast.literal_eval):
        try:
            return fn(raw), None
        except Exception:
            pass
    # 模型偶尔会在 JSON 前后加说明文字：截取最外层 [ ] 或 { } 再试
    for a, b in (("[", "]"), ("{", "}")):
        i, j = raw.find(a), raw.rfind(b)
        if i != -1 and j > i:
            sub = raw[i:j + 1]
            for fn in (json.loads, ast.literal_eval):
                try:
                    return fn(sub), None
                except Exception:
                    pass
    return None, raw

def 解包列表(结果):
    """模型偶尔把数组包在对象里（如 {"结果": [...]}），取出第一个列表；没有则原样返回。"""
    if isinstance(结果, dict):
        for v in 结果.values():
            if isinstance(v, list):
                return v
    return 结果

def 校验识别(raw):
    """识别结果要同时满足：是 JSON 数组、题号不空、题号不重复。
    题号重复会让后续判卷结果错位（学生作答张冠李戴），所以发现重复就判失败、换模型重试。"""
    结果, _ = 解析(raw)
    结果 = 解包列表(结果)
    if not (isinstance(结果, list) and len(结果) > 0 and all(isinstance(t, dict) for t in 结果)):
        return False, "不是有效 JSON 数组"
    题号 = [str(t.get("题号", "")).strip() for t in 结果]
    if any((not x) or x == "?" for x in 题号):
        return False, "存在空题号或占位题号"
    if len(set(题号)) != len(题号):
        重复 = [x for x in set(题号) if 题号.count(x) > 1]
        return False, f"题号重复：{'、'.join(重复)}"
    return True, ""

def 校验判卷(raw):
    """判卷结果必须能解析为「非空」的 JSON 数组，否则视为模型失败，交给下一个模型重试。"""
    结果, _ = 解析(raw)
    结果 = 解包列表(结果)
    if isinstance(结果, list) and len(结果) > 0:
        return True, ""
    return False, "不是有效 JSON 数组"

def 题号规范(x):
    """把 "1(2)"、"1（2）"、"1( 2 )" 统一成 "1(2)"；"１" 之类全角数字也转半角。"""
    s = str(x or "").strip()
    for a, b in [("（", "("), ("）", ")"), ("（", "("), ("　", " ")]:
        s = s.replace(a, b)
    s = s.replace(" ", "")
    s = "".join(chr(ord(c) - 0xFEE0) if "０" <= c <= "９" else c for c in s)
    s = re.sub(r"\((\d+)\)", r"(\1)", s)
    s = re.sub(r"^\d+\.", lambda m: m.group(0)[:-1], s)  # 去掉 "1." 这种点号
    return s

题号格式 = re.compile(r"^\d+(\s*\(\s*\d+\s*\))?$")

def 校验题号(raw):
    """第一步只识别题号：必须是 JSON 数组，题号非空、唯一、格式为 "3" 或 "1(2)"。
    格式或层级不对（如只有 "(1)"、两个相同题号）一律判失败，换模型重试——
    否则学生在勾选时就会选到错乱的题号。"""
    结果, _ = 解析(raw)
    结果 = 解包列表(结果)
    if not (isinstance(结果, list) and len(结果) > 0):
        return False, "不是有效 JSON 数组"
    号们 = []
    for x in 结果:
        if isinstance(x, str):
            号们.append(题号规范(x))
        elif isinstance(x, dict):
            号们.append(题号规范(x.get("题号", "")))
        else:
            号们.append("")
    if any(not x for x in 号们):
        return False, "存在空题号"
    if len(set(号们)) != len(号们):
        重复 = [x for x in set(号们) if 号们.count(x) > 1]
        return False, f"题号重复：{'、'.join(重复)}"
    坏 = [x for x in 号们 if not 题号格式.match(x)]
    if 坏:
        return False, f"题号格式不对（应为 1 或 1(2)）：{'、'.join(坏[:3])}"
    return True, ""

def 校验精识别(raw, 期望题号):
    """精识别只转写勾选的题：题号必须与勾选集合完全一致（不能多、不能少、不能改名）。"""
    结果, _ = 解析(raw)
    结果 = 解包列表(结果)
    if not (isinstance(结果, list) and len(结果) > 0 and all(isinstance(t, dict) for t in 结果)):
        return False, "不是有效 JSON 数组"
    实际 = [题号规范(t.get("题号", "")) for t in 结果]
    if any(not x for x in 实际):
        return False, "存在空题号"
    期望 = [题号规范(x) for x in 期望题号]
    if set(实际) != set(期望):
        多 = [x for x in 实际 if x not in 期望]
        少 = [x for x in 期望 if x not in 实际]
        提示 = []
        if 多:
            提示.append(f"多出 {'、'.join(多)}")
        if 少:
            提示.append(f"缺少 {'、'.join(少)}")
        return False, "题号与勾选不一致（" + "；".join(提示) + "）"
    return True, ""

def 校验文本(raw):
    """答疑这类纯文本输出：只要不是空话、不是报错，就算通过。"""
    t = (raw or "").strip()
    if len(t) >= 15:
        return True, ""
    return False, "回答为空或过短"

def 清理数学文本(s):
    if not isinstance(s, str): return s
    s = s.replace("\x0c", "\\f").replace("\\(", "$").replace("\\)", "$")
    return s.replace("\\[", "$$").replace("\\]", "$$")

