def 压缩图片(字节, 长边=1080, 质量=75):
    """先压图再传视觉模型：长边 1280px、JPEG 质量 78。
    图片越小，视觉 token 越少、上传越快，识别总时间明显缩短；A4 试卷 1280px 仍看得清题面。
    没装 Pillow 或失败时原样返回。"""
    try:
        from PIL import Image
        import io
        img = Image.open(io.BytesIO(字节))
        if img.mode in ("RGBA", "P"):
            img = img.convert("RGB")
        w, h = img.size
        if max(w, h) > 长边:
            r = 长边 / max(w, h)
            img = img.resize((int(w * r), int(h * r)), Image.LANCZOS)
        buf = io.BytesIO()
        img.save(buf, format="JPEG", quality=质量)
        return buf.getvalue(), "image/jpeg"
    except Exception:
        return 字节, None

def 命中章节(文本, 章):
    """按关键词判断这些题涉及哪几章；判断不清（0 章或超过 2 章）就返回 None。"""
